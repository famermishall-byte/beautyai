// Когда показывалась фирменная заставка (кольца + лого + слоган) — общая логика для сервера
// (layout.tsx решает, рисовать ли её вообще в SSR-разметке) и клиента (AppSplashGate.tsx пишет
// метку после показа). Раньше решение принималось только на клиенте через localStorage/эффект —
// но пока JS на телефоне грузится и гидратируется (на медленном соединении это заметно дольше,
// чем на компьютере), браузер уже успевает нарисовать исходный HTML, где заставка по умолчанию
// видна — и только потом клиентский эффект её прячет. На телефоне это выглядело как «заставка
// всё равно выскакивает» даже на обычном обновлении страницы (жалоба владельца, 24.09), хотя
// логика её скрытия технически отрабатывала — просто позже, чем успевал увидеть глаз. Cookie
// читается уже на сервере, до всякой гидратации — сервер сразу решает не рисовать заставку,
// если её показывали недавно, и никакого «моргания» просто не из чего возникнуть.
export const SPLASH_COOKIE = "beautyai-splash-last-shown";
const SPLASH_REOPEN_GAP_MS = 20 * 60 * 1000;

export function splashRecentlyShown(lastShownRaw: string | undefined | null): boolean {
  const last = Number(lastShownRaw ?? 0);
  return Number.isFinite(last) && Date.now() - last < SPLASH_REOPEN_GAP_MS;
}
