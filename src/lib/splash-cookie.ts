// Когда показывать фирменную заставку (анимированный логотип). Правило владельца (06.10): ТОЛЬКО когда клиент
// открывает приложение (в том числе первый раз после регистрации) и когда сотрудник переключается из админки в магазин.
// Не показывать на обновлении страницы (F5, «потяни вниз»), на переходах и на входе/выходе в рабочей сессии.
//
// Как отличаем «открыли приложение» от «работаем в нём»: пока приложение открыто, оно раз в 30 секунд обновляет
// cookie-«метку активности» со сроком жизни 2 минуты (AppSplashGate.tsx). Закрыли приложение — через 2 минуты метка
// исчезает, и следующая загрузка видит «метки нет» = открытие. Решение принимает СЕРВЕР до отрисовки (layout.tsx),
// так что заставка не мигает на обновлении (жалоба владельца 24.09). Сроком жизни cookie управляет браузер, а не
// сравнение времени с часами телефона: часы устройства могут врать.

/** Метка «приложение сейчас открыто»; живёт ACTIVE_TTL_SECONDS и обновляется, пока приложение открыто. */
export const ACTIVE_COOKIE = "beautyai-active";
export const ACTIVE_TTL_SECONDS = 120;
export const ACTIVE_REFRESH_MS = 30_000;

/** Одноразовая просьба «покажи заставку при следующей загрузке» — её ставит переключение «В магазин» (view-mode.ts). */
export const SPLASH_FORCE_COOKIE = "beautyai-splash-force";

/** Свёрнутое приложение, в которое вернулись через столько времени, проигрывает заставку заново (только установленное). */
export const RESUME_GAP_MS = 10 * 60 * 1000;

export function shouldShowSplash(input: { hasActiveMark: boolean; forced: boolean }): boolean {
  if (input.forced) return true; // переключение из админки в магазин — показываем всегда
  // Метка есть → приложение уже открыто, это обновление/переход внутри работы. Метки нет → приложение было закрыто
  // (или это самый первый вход) — открытие. Обновление в работе метку не теряет: пока страница видна, она
  // обновляется каждые ACTIVE_REFRESH_MS и при возврате в приложение.
  return !input.hasActiveMark;
}
