// Что приложение хранит на устройстве о самом человеке (а не просто настройки вроде языка или города).
// При выходе из аккаунта это убирается: следующий человек на этом телефоне не должен увидеть чужой адрес
// в форме заказа или чужие координаты.

const PERSONAL_KEYS = [
  "beautyai-delivery-address", // город, улица, дом, квартира — подставлялись в форму заказа
  "beautyai-coords", // координаты после «Разрешить геолокацию»
  "beautyai-cart", // старая корзина до переноса в аккаунт
];

export function clearPersonalDeviceData() {
  for (const key of PERSONAL_KEYS) {
    try {
      localStorage.removeItem(key);
    } catch {
      // хранилище недоступно — убирать нечего
    }
  }
}
