-- Источники импорта (import_templates) — только владельцу и администратору.
--
-- Было: политика import_templates_select_same_store разрешала ЧИТАТЬ источники любому пользователю
-- магазина, включая покупателей. В настройках источника (connection_config) лежат адрес таблицы
-- магазина и доступ к ней, поэтому покупателям это видеть нельзя.
--
-- Стало: политика чтения «для всех» убрана. Читать и менять источники по-прежнему могут владелец и
-- администратор — через политику import_templates_admin_write (она действует на все операции,
-- включая чтение). Ночная синхронизация (/api/cron/sync-sources) ходит с сервисным ключом и политик
-- не касается.
--
-- Ничего не удаляет из данных. Можно запускать повторно.

drop policy if exists import_templates_select_same_store on public.import_templates;
